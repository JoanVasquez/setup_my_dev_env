# Shared POSIX-compatible aliases (used by Bash and Zsh)
# Navigation/display shortcuts.
alias c='clear'
alias ll='ls -lah'
alias la='ls -A'
# Git shortcuts preserve any additional arguments typed after the alias.
alias g='git'
alias gs='git status'
alias ga='git add'
alias gc='git commit'
alias gp='git push'
alias gl='git pull'
alias gd='git diff'
# Docker shortcuts use the modern Compose plugin (`docker compose`).
alias d='docker'
alias dc='docker compose'
alias dps='docker ps'
# Editor and session manager shortcuts.
alias n='nvim'
alias t='tmux'
